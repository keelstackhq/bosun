//! Signed owner approvals (spec §8): `/bosun approve <head>` plus a `bosun-sig ed25519` line
//! from a key enrolled in `.bosun/approvers.toml` on the default branch.
mod common;

use common::fake::FakeGithub;
use common::{bosun, one_object, run};
use serde_json::{Value, json};

const NOW: &str = "2026-10-22T10:00:00Z";
const BASE: &str = "base0000";
const HEAD: &str = "0123456789abcdef0123456789abcdef01234567";
const OLD: &str = "1111111111111111111111111111111111111111";
const OWNERS: &str = "[[owner]]\ngithub = \"ada\"\n";

// RFC 8032 test 1 key; its PKCS#8 PEM is what `openssl pkey` writes for that seed.
const PEM: &str = "-----BEGIN PRIVATE KEY-----\nMC4CAQAwBQYDK2VwBCIEIJ1hsZ3v/VpguoRK9JLsLMREScVpezJpGXA7rAMcrn9g\n-----END PRIVATE KEY-----\n";
const PUB: &str = "11qYAYKxCrfVS/7TyWQHOg7hcvPapiMlrwIaaPcHURo=";
// RFC 8032 test 2 key: never enrolled on main.
const PUB2: &str = "PUAXw+hDiVqStwqnTRt+vJyYLM8uxJaMwM1V8Sr0Zgw=";

// Made with `openssl pkeyutl -sign -rawin -inkey key.pem -in msg`, msg as printf '%s' writes it.
/// `bosun-approve v1 acme/widget#1 <HEAD>`
const SIG: &str =
    "dTnLJ8NM8jp0umTiTZRuGW0lwGdxPoLlu069r9NXkSyrLmKj3SBW1ULZrmXNsE/qzfn+5gY0INdSAqttzPxmBg==";
/// `bosun-approve v1 acme/widget#2 <HEAD>`
const SIG_PR2: &str =
    "nfCtaHHbNLhbBf1NTS2VqZGH634/mibKN73JBsoiBkS1ADwVi81zjLJcVApmLIN/YbpzKPTcO2wj05ldV8QMAw==";
/// `bosun-approve v1 acme/gadget#1 <HEAD>`
const SIG_REPO: &str =
    "n1XTT/ePk3qTDu4WUnCjq8T5fXWecq30epkpx3ZCysvyFUtLPTIdkzccHDNrXqbcULe4wCHtOCad3yQQLKlwDQ==";
/// `bosun-approve v1 acme/widget#1 <OLD>`
const SIG_OLD: &str =
    "b33sAFpd2Visck7gZAiLKqgADH3vZ+dXsOq4px4nqL2xN/wqMdaxaM5uB7hrhY6OYnKet65mBy0l2iqsqFfaCA==";
/// `bosun-approve v1 acme/widget#1 <HEAD>` with the test 2 key.
const SIG_KEY2: &str =
    "QaSlWA89SY/lbC3KRhb7YMRUCs8twG1ipEnTH1RI7j3C6YmLPO5fj5lhr5Sm4hBYozbu0XKkPfWAOunh4IYfBQ==";

fn approvers(keys: &[(&str, &str)]) -> String {
    keys.iter()
        .map(|(id, k)| format!("[[key]]\nid = \"{id}\"\ned25519 = \"{k}\"\n"))
        .collect::<Vec<_>>()
        .join("\n")
}

fn body(sha: &str, id: &str, sig: &str) -> String {
    format!(
        "/bosun approve {sha}\n\nApproved in chat.\nbosun-sig ed25519 {id} {sig}\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    )
}

/// High PR 1 at HEAD, owners at base, key `k1` (test 1) enrolled on main.
fn high_pr() -> FakeGithub {
    let fake = FakeGithub::start();
    fake.pull(1, "change", "feature", "");
    fake.pull_as_issue(1, "change");
    fake.pull_set(1, "head", json!({"sha": HEAD, "ref": "feature"}));
    fake.content("governance/owners.toml", BASE, OWNERS);
    fake.content(".bosun/approvers.toml", "main", &approvers(&[("k1", PUB)]));
    fake.pull_file(
        1,
        ".github/workflows/ci.yml",
        "modified",
        1,
        0,
        Some("@@ -0,0 +1,1 @@\n+x"),
    );
    fake
}

fn check(fake: &FakeGithub) -> (i32, Value) {
    run(fake, "session_test", NOW, &["risk-check", "1"])
}

/// A comment through the Claude app, as the cloud proxy posts it.
fn app_comment(fake: &FakeGithub, text: &str) {
    fake.comment_by(1, "claude", text);
    fake.last_comment(|c| c.via_app = Some("claude".into()));
}

#[test]
fn a_signature_from_an_enrolled_key_approves_through_an_app() {
    let fake = high_pr();
    app_comment(&fake, &body(HEAD, "k1", SIG));
    // Edits do not matter: the signature binds the approval, not the comment.
    fake.last_comment(|c| c.updated_at = "2026-10-22T11:00:00Z".into());
    let (code, v) = check(&fake);
    assert_eq!(code, 0, "{v}");
    assert_eq!(v["data"]["approved_by"], "key k1");
    let s = fake.statuses_of(HEAD);
    let s = s
        .iter()
        .rev()
        .find(|s| s["context"] == "risk-check")
        .unwrap();
    assert_eq!(s["state"], "success");
    assert!(
        s["description"]
            .as_str()
            .unwrap()
            .ends_with("approved by key k1")
    );

    // An owner's request-changes review on the head withdraws it.
    fake.review(1, "ada", "CHANGES_REQUESTED", HEAD);
    assert_eq!(check(&fake).0, 5);
}

#[test]
fn replays_and_forgeries_do_not_count() {
    let fake = high_pr();
    let bad = [
        body(HEAD, "k1", SIG_PR2),                // signed for another PR
        body(HEAD, "k1", SIG_REPO),               // signed for another repo
        body(HEAD, "k1", SIG_OLD),                // signed for an old head
        body(OLD, "k1", SIG_OLD),                 // the old head, both lines
        body(HEAD, "k9", SIG),                    // unknown key id
        body(HEAD, "k1", &SIG.replace('d', "e")), // bad signature
        body(HEAD, "k1", "not-base64!"),          // malformed signature
        body(HEAD, "k1", "AAAA"),                 // wrong length
        format!("/bosun approve {HEAD}\nbosun-sig ed25519 k1 {SIG} extra"),
        format!("/bosun approve {HEAD}\n> bosun-sig ed25519 k1 {SIG}"),
        format!("/bosun approve {HEAD}\nbosun-sig rsa k1 {SIG}"),
        format!("Approved.\n/bosun approve {HEAD}\nbosun-sig ed25519 k1 {SIG}"), // not line 1
        format!("bosun-sig ed25519 k1 {SIG}\n/bosun approve {HEAD}"),
        format!("/bosun approve {HEAD} now\nbosun-sig ed25519 k1 {SIG}"),
    ];
    for b in &bad {
        app_comment(&fake, b);
    }
    let out = bosun()
        .env("BOSUN_GITHUB_API", fake.url())
        .args(["risk-check", "1"])
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(5), "none of these approves");
    let v = one_object(&out.stdout);
    assert_eq!(v["data"]["approved_by"], Value::Null);
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(err.contains("unknown key"), "{err}");
    assert!(err.contains("does not verify"), "{err}");

    // A valid signature line among bad ones still counts: each line is checked on its own.
    app_comment(
        &fake,
        &format!(
            "/bosun approve {HEAD}\nbosun-sig ed25519 k1 {SIG_OLD}\nbosun-sig ed25519 k1 {SIG}"
        ),
    );
    assert_eq!(check(&fake).0, 0);
}

#[test]
fn a_key_only_on_the_pr_head_or_base_does_not_count() {
    let fake = high_pr();
    let both = approvers(&[("k1", PUB), ("k2", PUB2)]);
    fake.content(".bosun/approvers.toml", "feature", &both);
    fake.content(".bosun/approvers.toml", HEAD, &both);
    fake.content(".bosun/approvers.toml", BASE, &both);
    fake.pull_file(
        1,
        ".bosun/approvers.toml",
        "modified",
        1,
        0,
        Some("@@ -0,0 +1,1 @@\n+k2"),
    );
    app_comment(&fake, &body(HEAD, "k2", SIG_KEY2));
    assert_eq!(check(&fake).0, 5, "the PR adds its own key: no approval");
}

#[test]
fn missing_or_malformed_approvers_turn_the_feature_off_without_an_error() {
    let fake = high_pr();
    app_comment(&fake, &body(HEAD, "k1", SIG));
    for text in [
        "not toml [[",
        "[[key]]\nid = \"k1\"\ned25519 = \"AAAA\"\n",
        "[[key]]\nid = \"k1\"\n",
    ] {
        fake.content(".bosun/approvers.toml", "main", text);
        let (code, v) = check(&fake);
        assert_eq!(code, 5, "{text}: {v}");
    }
    // A duplicate id is malformed: two keys under one name would make the record ambiguous.
    fake.content(
        ".bosun/approvers.toml",
        "main",
        &approvers(&[("k1", PUB2), ("k1", PUB)]),
    );
    assert_eq!(check(&fake).0, 5, "duplicate ids");
    fake.state
        .lock()
        .unwrap()
        .contents
        .remove("main:.bosun/approvers.toml");
    assert_eq!(check(&fake).0, 5, "no file: the feature is off");
}

