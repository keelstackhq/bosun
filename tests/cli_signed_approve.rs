fn key_file() -> std::path::PathBuf {
    let dir = tempfile::tempdir().unwrap().keep();
    let path = dir.join("key.pem");
    std::fs::write(&path, PEM).unwrap();
    path
}

fn sign_cmd(fake: &FakeGithub, cloud: bool) -> assert_cmd::Command {
    let mut cmd = bosun();
    cmd.env("BOSUN_GITHUB_API", fake.url());
    if cloud {
        cmd.env("CCR_AGENT_PROXY_ENABLED", "true");
    }
    cmd
}

#[test]
fn approve_sign_key_print_matches_openssl_and_posts_nothing() {
    let fake = high_pr();
    let key = key_file();
    let out = sign_cmd(&fake, true)
        .args(["approve", "1", "--print", "--sign-key"])
        .arg(&key)
        .output()
        .unwrap();
    let v = one_object(&out.stdout);
    assert_eq!(out.status.code(), Some(0), "{v}");
    let text = v["data"]["body"].as_str().unwrap();
    assert_eq!(
        text,
        format!("/bosun approve {HEAD}\nbosun-sig ed25519 k1 {SIG}")
    );
    assert_eq!(v["data"]["head_sha"], HEAD);
    assert!(!format!("{v}{}", String::from_utf8_lossy(&out.stderr)).contains("MC4CAQAw"));
    assert!(
        fake.state.lock().unwrap().comments.is_empty(),
        "--print posts nothing"
    );
}

#[test]
fn approve_sign_key_posts_in_the_cloud_and_risk_check_accepts_it() {
    let fake = high_pr();
    let key = key_file();
    let out = sign_cmd(&fake, true)
        .args(["approve", "1", "--sign-key"])
        .arg(&key)
        .output()
        .unwrap();
    let v = one_object(&out.stdout);
    assert_eq!(out.status.code(), Some(0), "{v}");
    assert_eq!(v["data"]["approved"][0]["pr"], 1);
    assert_eq!(v["data"]["approved"][0]["head_sha"], HEAD);
    // The fake posts as the token's login, through no app; risk-check counts the signature.
    fake.last_comment(|c| c.via_app = Some("claude".into()));
    let (code, v) = check(&fake);
    assert_eq!(code, 0, "{v}");
    assert_eq!(v["data"]["approved_by"], "key k1");
}

#[test]
fn approve_sign_key_errors() {
    let fake = high_pr();
    // A key file that is not an ed25519 PKCS#8 PEM: exit 1, the file content never printed.
    let dir = tempfile::tempdir().unwrap();
    let bad = dir.path().join("bad.pem");
    std::fs::write(
        &bad,
        "-----BEGIN PRIVATE KEY-----\nc2VjcmV0LWNhbmFyeQ==\n-----END PRIVATE KEY-----\n",
    )
    .unwrap();
    let out = sign_cmd(&fake, false)
        .args(["approve", "1", "--sign-key"])
        .arg(&bad)
        .output()
        .unwrap();
    let v = one_object(&out.stdout);
    assert_eq!(out.status.code(), Some(1), "{v}");
    let all = format!("{v}{}", String::from_utf8_lossy(&out.stderr));
    assert!(
        !all.contains("c2VjcmV0") && !all.contains("secret-canary"),
        "{all}"
    );

    // The key is not enrolled on main: refused before posting.
    fake.content(".bosun/approvers.toml", "main", &approvers(&[("k2", PUB2)]));
    let out = sign_cmd(&fake, false)
        .args(["approve", "1", "--sign-key"])
        .arg(key_file())
        .output()
        .unwrap();
    let v = one_object(&out.stdout);
    assert_eq!(out.status.code(), Some(1), "{v}");
    assert!(fake.state.lock().unwrap().comments.is_empty());

    // Without --sign-key the cloud refusal still applies, and a bare PR number is a usage error.
    let out = sign_cmd(&fake, true)
        .env("BOSUN_OWNER_TOKEN", "t")
        .args(["approve", &format!("1@{HEAD}")])
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(5));
    let out = sign_cmd(&fake, false)
        .args(["approve", "1"])
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(2));
    // --print needs --sign-key.
    let out = sign_cmd(&fake, false)
        .args(["approve", "1", "--print"])
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(2));
}

